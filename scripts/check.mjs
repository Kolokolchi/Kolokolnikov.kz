// Pages generated by scripts/build-seo.mjs live in projects/ and video/; assembly scenes are iframes.
const pages=[...files.filter(name=>name.endsWith('.html')),'demos/index.html',...(await readdir(root,{recursive:true})).filter(name=>/^(projects|video)[\\/].*\.html$/.test(name)).map(name=>name.replaceAll('\\','/'))];
for(const name of pages){
  const html=await readFile(path.join(root,name),'utf8');
  assert.match(html,/<html lang="ru"/);
  assert.match(html,/<meta name="viewport"/);
  // 404.html is served at any depth and resolves its links from <base>, i.e. the site root.
  const from=/<base href=/.test(html)?root:path.join(root,path.dirname(name));
  for(const [,target] of html.replace(/<base [^>]*>/,'').matchAll(/(?:href|src)="([^"?#]+)(?:[?#][^"]*)?"/g)){
    if(/^(https?:|mailto:|tel:)/.test(target)||target==='./')continue;
    if(/(?:^|\/)demos\/[a-z0-9-]+\/$/.test(target))continue; // uploaded demos are served by the Sites worker from R2
    let resolved=path.resolve(from,target);
    if((await stat(resolved)).isDirectory())resolved=path.join(resolved,'index.html');
    assert.ok((await stat(resolved)).isFile(),`${name}: ${target}`);
  }
}

// SEO gate: every page with a canonical URL is indexable and complete; the sitemap lists exactly those.
const {DEFAULT_SITE_URL}=await import('./build-seo.mjs');
const attr=(html,pattern)=>html.match(pattern)?.[1];
const indexable=new Map();
for(const name of pages){
  const html=await readFile(path.join(root,name),'utf8');
  const canonical=attr(html,/<link rel="canonical" href="([^"]+)"/);
  if(!canonical){assert.match(html,/<meta name="robots" content="noindex/,`${name}: add a canonical URL or noindex`);continue;}
  assert.doesNotMatch(html,/<meta name="robots" content="[^"]*noindex/,`${name}: canonical page must not be noindex`);
  assert.ok(canonical.startsWith(DEFAULT_SITE_URL),`${name}: canonical outside ${DEFAULT_SITE_URL}`);
  assert.equal([...html.matchAll(/<h1[\s>]/g)].length,1,`${name}: exactly one <h1>`);
  const title=attr(html,/<title>([^<]+)<\/title>/)??'';
  const description=attr(html,/<meta name="description" content="([^"]+)"/)??'';
  assert.ok(title.length>10&&title.length<=60,`${name}: title length ${title.length} (≤60)`);
  assert.ok(description.length>=120&&description.length<=160,`${name}: description length ${description.length} (120–160)`);
  for(const property of ['og:title','og:description','og:url','og:image','og:type'])assert.match(html,new RegExp(`<meta property="${property}" content="[^"]+"`),`${name}: ${property}`);
  assert.match(attr(html,/<meta property="og:image" content="([^"]+)"/),/^https:\/\//,`${name}: og:image must be absolute HTTPS`);
  assert.match(html,/<meta name="twitter:card" content="summary_large_image">/,`${name}: twitter:card`);
  const ld=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  assert.ok(ld.length,`${name}: JSON-LD`);
  for(const [,json] of ld)JSON.parse(json);
  // Headings descend one level at a time (h1 → h2 → h3), as written in the static HTML.
  let level=0;
  for(const [,depth] of html.replace(/<(?:noscript|template)[\s\S]*?<\/(?:noscript|template)>/g,'').matchAll(/<h([1-6])[\s>]/g)){assert.ok(Number(depth)<=level+1,`${name}: heading jumps to h${depth} after h${level}`);level=Number(depth);}
  indexable.set(canonical,name);
}
